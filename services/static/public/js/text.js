// Catalog keys that code asked for and the catalog does not have
var uiTextMissing = [];

function uiTextValue(key) {
    var v = Object.prototype.hasOwnProperty.call(UI_TEXT, key) ? UI_TEXT[key] : undefined;
    if (v === undefined) {
        // Kept in memory for a developer, not printed: the console gets a fixed message only
        if (uiTextMissing.indexOf(key) === -1) uiTextMissing.push(key);
        if (typeof console !== "undefined") console.error("UI_TEXT is missing a key; see uiTextMissing");
        return undefined;
    }
    return v;
}

function uiTextFill(text, vars, each) {
    return String(text).replace(/\{(\w+)\}/g, function (whole, name) {
        if (!vars || !Object.prototype.hasOwnProperty.call(vars, name)) return whole;
        return each(vars[name]);
    });
}

// The plain text of key, its {name} placeholders replaced by String(vars.name)
function t(key, vars) {
    var v = uiTextValue(key);
    if (v === undefined) return "";
    if (typeof v !== "string") v = v.other;
    return uiTextFill(v, vars, function (x) { return String(x); });
}

function uiTextCount(n) {
    return Number(n || 0).toLocaleString();
}

var uiTextPlural = typeof Intl !== "undefined" && Intl.PluralRules ? new Intl.PluralRules("en") : null;

// A count: the one or other form of key for n, with {n} as a formatted number
function tn(key, n, vars) {
    var v = uiTextValue(key);
    if (v === undefined) return "";
    var form = typeof v === "string" ? v : (uiTextPlural ? uiTextPlural.select(Number(n)) : Number(n) === 1 ? "one" : "other") === "one" ? v.one : v.other;
    var all = { n: uiTextCount(n) };
    if (vars) for (var k in vars) if (Object.prototype.hasOwnProperty.call(vars, k)) all[k] = vars[k];
    return uiTextFill(form, all, function (x) { return String(x); });
}

// Markup the code built itself from escaped parts, for a variable of tHtml()
function tRaw(html) {
    return { uiTextRaw: String(html) };
}

function uiTextEscape(value) {
    return String(value === null || value === undefined ? "" : value)
        .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;").replace(/'/g, "&#39;");
}

// The catalog text escaped as a whole, then its variables put in: each one
// escaped, unless the code wrapped it in tRaw()
function tHtml(key, vars) {
    var v = uiTextValue(key);
    if (v === undefined) return "";
    if (typeof v !== "string") v = v.other;
    return uiTextFill(uiTextEscape(v), vars, function (x) {
        return x && typeof x === "object" && Object.prototype.hasOwnProperty.call(x, "uiTextRaw") ? x.uiTextRaw : uiTextEscape(x);
    });
}

// Elements whose words are in place; the passes while the page is parsed skip them
var uiTextDone = typeof WeakSet !== "undefined" ? { p: new WeakSet(), t: new WeakSet(), a: new WeakSet() } : null;

// Words of the HTML pages: data-t="key" sets the text of an element whose whole
// content is that text; data-t-attr="aria-label:key;title:key" sets attributes;
// data-t-tpl="key" fills an element from a value whose {name} placeholders are
// its child elements marked data-t-slot="name", which are kept, not rebuilt.
// onlyNew: skip elements already done, and a template whose slots the parser
// has not added yet (it is filled once they are there).
function uiApplyText(root, onlyNew) {
    var scope = root || document;
    var all = function (sel) {
        var found = scope.querySelectorAll ? Array.prototype.slice.call(scope.querySelectorAll(sel)) : [];
        if (scope.matches && scope.matches(sel)) found.unshift(scope);
        return found;
    };
    var fresh = function (el, kind) { return !onlyNew || !uiTextDone || !uiTextDone[kind].has(el); };
    var mark = function (el, kind) { if (uiTextDone) uiTextDone[kind].add(el); };
    all("[data-t-tpl]").forEach(function (el) {
        if (!fresh(el, "p")) return;
        var slots = {};
        Array.prototype.forEach.call(el.children, function (child) {
            var name = child.getAttribute("data-t-slot");
            if (name) slots[name] = child;
        });
        var v = uiTextValue(el.getAttribute("data-t-tpl"));
        if (v === undefined) return;
        var parts = String(v).split(/(\{\w+\})/);
        if (onlyNew && parts.some(function (part) { var m = /^\{(\w+)\}$/.exec(part); return m && !slots[m[1]]; })) return;
        while (el.firstChild) el.removeChild(el.firstChild);
        parts.forEach(function (part) {
            var m = /^\{(\w+)\}$/.exec(part);
            if (m && slots[m[1]]) el.appendChild(slots[m[1]]);
            else if (part) el.appendChild(document.createTextNode(part));
        });
        mark(el, "p");
    });
    all("[data-t]").forEach(function (el) {
        if (!fresh(el, "t")) return;
        el.textContent = t(el.getAttribute("data-t"));
        mark(el, "t");
    });
    all("[data-t-attr]").forEach(function (el) {
        if (!fresh(el, "a")) return;
        el.getAttribute("data-t-attr").split(";").forEach(function (pair) {
            var at = pair.indexOf(":");
            if (at > 0) el.setAttribute(pair.slice(0, at).trim(), t(pair.slice(at + 1).trim()));
        });
        mark(el, "a");
    });
}

// The page's own words from its first paint: what is parsed when this script
// runs (the <title> and the meta description), then every element as the parser
// adds it. A MutationObserver answers before the browser paints what was added.
// The pages' last script calls uiApplyText(document, true) again, and so does
// DOMContentLoaded; both only fill what is still empty, so neither rewrites a
// word a script has changed since.
function uiApplyTextWhileParsing() {
    uiApplyText(document, true);
    if (document.readyState !== "loading") return;
    var observer = null;
    if (typeof MutationObserver === "function") {
        observer = new MutationObserver(function (records) {
            records.forEach(function (record) {
                Array.prototype.forEach.call(record.addedNodes, function (node) {
                    if (node.nodeType === 1) uiApplyText(node, true);
                });
                // A template waits for its slots: try it again when its children change
                var tpl = record.target && record.target.nodeType === 1 && record.target.closest ? record.target.closest("[data-t-tpl]") : null;
                if (tpl) uiApplyText(tpl, true);
            });
        });
        observer.observe(document.documentElement, { childList: true, subtree: true });
    }
    document.addEventListener("DOMContentLoaded", function () {
        if (observer) observer.disconnect();
        uiApplyText(document, true);
    });
}

if (typeof document !== "undefined" && document && typeof document.addEventListener === "function" && typeof document.querySelectorAll === "function") {
    uiApplyTextWhileParsing();
}
